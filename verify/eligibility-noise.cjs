/* 자격 자리에 들어간 '요건이 아닌 줄'을 가르는 규칙 — **한 곳뿐이다.**
   채점기(eligibility-report.mjs)와 관문(audit-data.js)이 같은 규칙을 각각 베껴 갖고 있었고,
   그래서 한쪽만 고치면 "감사는 통과하는데 화면엔 잡음이 뜨는" 상태가 됐다 (2026-08-24).

   ⚠️ 이 규칙은 화면 필터(match-engine)와 **일부러 다른 축**이다 —
   "조건을 말하는가"가 아니라 "제목·목록·표·순위처럼 생겼는가".
   같은 규칙을 쓰면 필터의 눈으로 필터를 채점하는 셈이라 새 유형을 영영 못 본다. */

/* 괄호 **안**의 '지원불가'는 요건에 붙은 부연이다 — `2026년 2학기 재학생 (휴학예정자 지원불가)`.
   이걸 제외 줄로 세면 멀쩡한 요건 10건이 오류로 잡혀 감사가 저장을 막는다. */
const EXCLUDE_RE = /(제외(한다|합니다|됨|대상)?\s*$|받은\s*(학생|자)는?\s*제외|지원\s*불가|신청\s*불가|중복\s*수혜\s*불가)/;
/* 면제·산정 규칙 — 사람을 빼는 말이 아니다(위 NOISE_KIND 주석 참조) */
const EXEMPT_RE = /(기준\s*)?적용\s*제외|미적용|산정.{0,6}제외|학점\s*제외|계절.{0,10}제외|을\s*제외한|를\s*제외한|제외하고/;
const outsideParens = (t) => {
  const bare = String(t).replace(/\s*[(（][^)）]*[)）]\s*$/, '').trim();
  return bare.length >= 4 ? bare : String(t);
};

/* 🔴 순위 기준 — 2026-08-24 개발자가 앱을 열자마자 세 건을 찾아낸 유형.
   `학년이 높은 학생` `누적 평균 평점이 높은 학생` `소득순위 순으로 선발` `성적상위자 우선 고려`.
   요건 낱말(학년·성적·구간)을 갖고 있어 통과 조건도 옛 채점기도 통째로 뚫렸다.
   ⚠️ 필터(match-engine의 RANK_LINE)보다 **일부러 넓게** 잡는다 — 좁게 베끼면
   필터가 놓친 것을 채점기도 똑같이 놓친다. 넓어서 생기는 오탐은 경고로 보면 된다. */
const RANK_RE = /(높은|낮은|우수한|많은|좋은)\s*(순|순서)?\s*(학생|자|사람|가정|순)|순으로\s*(선발|선정|지급|배정)|상위자|고득점자|성적순|점수순|우선\s?(선발|고려|검토|배정|선정|순위|함|한다|시)|우대\s*[).\]]*\s*$/;

const NOISE_KIND = {
  /* 🔴 '제외'가 붙었다고 다 제외가 아니다 — **면제·산정 규칙**은 오히려 학생에게 유리하다
     (2026-08-24 전수 조사). `신/편입생은 입학 학기에만 학점 및 성적 기준 적용 제외`를
     제외 줄로 세면, 화면이 그걸 '이런 경우는 제외돼요'로 옮겨 **신입생에게 너는 안 된다**고
     보여 준다 — 자격이 뒤집히는, 잡음보다 나쁜 실패다. `계절, 교류, 인정학점 제외`도
     사람을 빼는 말이 아니라 학점 세는 규칙이다.
     ⚠️ 이건 필터를 베낀 게 아니라 **규칙이 틀렸던 것**이다(면제 ≠ 제외). */
  '제외 대상 (자리가 틀렸다 — 제외 블록으로)': (t) =>
    EXCLUDE_RE.test(outsideParens(t)) && !EXEMPT_RE.test(t),
  '순위 기준 (자리가 틀렸다 — 먼저 뽑는 기준으로)': (t) => RANK_RE.test(t),
  '배점·평가': (t) => /(만점|배점|가점|점수\s*적용|반영\s*비율|평가\s*(항목|비율)|산정\s*(기간|방법)\s*$)/.test(t),
  '일정·기한': (t) => /(기한|기간)\s*[:：]|우편\s*도착분|\d{4}[.\-]\s?\d{1,2}[.\-]\s?\d{1,2}\s*(까지|마감)/.test(t),
  '선발·인원': (t) => /^(추천|선발|모집)\s*인원|(추천|선발|모집)\s*인원\s*[:：]/.test(t),
  /* 수량이 붙은 서류도 서류다 — `학자금 지원구간 확인서 1 부` (2026-08-24) */
  '제출·서류': (t) => /^(제출|구비)\s*서류|서식\s*[:：]|(증명서|확인서|신청서|동의서)\s*(각\s*)?\d*\s*[부통매장]/.test(t),
};

/* 조각은 좁게 잡는다 — 한글로 끝나는 줄을 전부 조각으로 세면 정상 문장이 다 걸려
   숫자가 뜻을 잃는다(처음에 그렇게 재서 303줄이 나왔다). 실제 표지만 쓴다. */
const FRAGMENT = /^[^()（）]*[(（][^)）]*$|^.{0,12}(기간|방법|기준|현황|내역|사항)\s*$|\s인\s*\(/;

/* 요건 신호가 뚜렷한 줄은 '자리가 틀린 것'만 문제 삼는다 — 그 밖의 유형은
   낱말 하나로 진짜 요건을 잡음이라 부른다(`한부모가족증명서 발급 대상 가정의 대학생`). */
const MISPLACED = /제외|순위|조각/;

module.exports = { NOISE_KIND, FRAGMENT, MISPLACED, RANK_RE, EXCLUDE_RE, outsideParens };
