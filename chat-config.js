/* ============================================================
   한대장 — 장학금 도우미(챗봇) 설정
   ------------------------------------------------------------
   도우미는 **두 겹**으로 되어 있다.

   ① 안내봇 (지금 켜져 있는 것 · 비용 0원)
      앱이 이미 갖고 있는 공고·서류·신청 현황만 보고 답한다. 열쇠도 서버도 필요 없고,
      비행기 모드에서도 답한다. 성적·소득 같은 개인 정보가 기기 밖으로 나가지 않는다.
      **지어낼 수가 없다** — 앱에 있는 것만 골라 보여 주는 구조라서.

   ② AI 답변 (지금은 꺼져 있음 · 아래 endpoint가 비어 있으면 아예 동작하지 않는다)
      안내봇이 **못 알아들은 질문에만** 쓴다. 이 저장소가 이미 쓰고 있는 방식과 같은 모양이다
      (신청서 자동 변환: 무료로 되는 건 무료로, 안 되는 것만 API).

   ⚠️ 열쇠(API 키)를 이 파일에 넣으면 안 된다. 저장소가 공개라 누구나 꺼내 쓴다.
      열쇠는 서버(Cloudflare Worker)에만 두고, 앱은 그 서버 주소만 안다.
      푸시 발송 서버(server/push/)와 똑같은 구조이고, 앱의 보안 설정(CSP)도
      workers.dev 주소를 이미 허용해 두었다.

   켜는 방법: 서버를 올리고 아래 endpoint 한 칸만 채우면 된다. 앱 코드는 고칠 것이 없다.
   ============================================================ */
const CHAT_CONFIG = {
  /* 예: 'https://handaejang-chat.○○○.workers.dev' — 비어 있으면 안내봇만 쓴다 */
  endpoint: '',

  /* 서버에 보내도 되는 것의 한계선 (되돌리지 말 것)
     - 질문 글자와, **앱이 먼저 골라 낸 공고의 공개 정보**만 보낸다.
     - 이름·학교·성적·소득구간·특별자격·계좌는 **절대 보내지 않는다.**
       판단은 지금처럼 기기 안에서 끝내고, 서버는 '고른 공고를 말로 풀어 주는' 일만 한다.
     - 그래서 서버가 뚫려도 새어 나갈 개인 정보가 없다. */
  maxItems: 6,      // 한 번에 서버로 넘기는 공고 수
  timeoutMs: 8000,  // 이 시간 안에 답이 없으면 안내봇 답으로 되돌아간다
};

/* AI 답변을 쓸 수 있는 상태인가 — 앱 곳곳에서 이 함수로만 판단한다 */
function chatAiConfigured() {
  return !!(CHAT_CONFIG && CHAT_CONFIG.endpoint);
}

if (typeof module !== 'undefined' && module.exports) module.exports = { CHAT_CONFIG, chatAiConfigured };
