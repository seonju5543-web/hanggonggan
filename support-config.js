/* ============================================================
   한대장 — 고객센터 문의처 설정
   ------------------------------------------------------------
   push-config.js · chat-config.js · supabase-config.js 와 **같은 방식**이다.
   아래 칸이 비어 있으면 그 기능이 화면에 아예 안 나온다 — 눌러도 아무 일이 없는
   가짜 버튼을 두지 않기 위해서다.

   🔴 지금은 일부러 비워 두었다. `terms.html` 9번(개인정보 보호책임자 및 문의처)이
      *"베타 기간에는 별도 문의처를 두지 않습니다. 서비스를 공개할 때 실제로 응대 가능한
      주소를 이 자리에 적고 그때부터 접수합니다"* 라고 적어 두었기 때문이다.
      여기에 주소를 채우면서 그 문장을 안 고치면, **약관과 앱이 서로 다른 말을 한다.**

   채우는 순서 (둘을 같이 해야 한다)
     ① 아래 email 에 실제로 받아 볼 수 있는 주소를 적는다
     ② terms.html 9번의 `legal-tmp` 문장을 같은 주소로 고친다
   그러면 고객센터 화면에 '문의 메일 쓰기' 버튼이 그 순간 나타난다(앱 코드 무변경).

   ⚠️ 개인 메일 주소를 적으면 학생 전체에게 공개된다. 서비스용 주소를 따로 만드는 것을 권한다.
   ============================================================ */
const SUPPORT_CONFIG = {
  /* 예: 'help@handaejang.kr' — 비어 있으면 '문의 메일 쓰기' 버튼이 나오지 않는다 */
  email: '',

  /* 예: '평일 10:00~18:00 (주말·공휴일 휴무)' — 비어 있으면 응대 시간을 **적지 않는다**.
     🔴 지키지 못할 시간을 적는 것은 없는 것보다 나쁘다(운영 원칙 1). */
  hours: '',
};

/* 문의처가 준비됐는가 — 화면 곳곳에서 이 함수로 판단한다 */
function supportConfigured() {
  return !!SUPPORT_CONFIG.email;
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { SUPPORT_CONFIG, supportConfigured };
}
