/* 게시판 목록에서 딸려 들어온 부스러기를 제목에서 걷어낸다.

   게시판마다 한 줄(<a> 안)에 번호·분류·조회수·작성일·기간을 함께 넣는 곳이 있어서,
   태그를 걷어내면 전부 한 문장으로 뭉쳐진다. 예(연세대 2026-07-30 연결 시 발견):
     "1383 2026학년도 2학기 염곡문화재단 장학생 추천 안내 새글 장학 조회수 868 작성일 2026.07.24"
   → "2026학년도 2학기 염곡문화재단 장학생 추천 안내"

   수집기(collect.mjs)와 자동 등록(auto-register.mjs)이 같은 규칙을 쓰도록 여기 모아 둔다. */

/* HTML 특수문자를 원래 글자로 되돌린다.
   게시판이 제목에 따옴표·괄호·부등호를 쓰면 HTML에는 &quot; &#40; &lt; 로 들어 있는데,
   태그만 걷어내면 이 글자들이 그대로 남아 앱 화면에 "&quot;근로지담당자&quot;" 처럼 보인다.
   (2026-08-02 가천·가톨릭·경기대를 붙이면서 발견 — 기존 게시판들은 안 쓰던 표기라 여태 안 드러났다) */
/* 🔴 **내보낸다** (2026-09-23) — 공고 원문을 학생 화면에 그대로 보여 주는 칸이 늘었다
   (`applyEmailSource`·`applyPortalSource`). 베껴 쓰면 한쪽만 고쳐져 갈라지므로 여기서 가져간다.
   ⚠️ 화살표·줄표는 **게시판이 실제로 내보내는 기호**다 — 실측으로 저장된 근거 문장에
      `&rarr;`·`&ndash;` 가 남아 학생 화면에 글자로 뜰 참이었다(2026-09-11 `&nbsp;` 사고와 같은 줄). */
export function decodeEntities(t) {
  return String(t || '')
    .replace(/&#(\d+);/g, (_, d) => String.fromCharCode(+d))
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCharCode(parseInt(h, 16)))
    .replace(/&quot;/g, '"').replace(/&apos;/g, "'")
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>')
    .replace(/&nbsp;/g, ' ')
    .replace(/&rarr;/g, '→').replace(/&larr;/g, '←')
    .replace(/&ndash;/g, '–').replace(/&mdash;/g, '—')
    .replace(/&middot;/g, '·').replace(/&hellip;/g, '…')
    .replace(/&amp;/g, '&');   // 반드시 마지막 — 먼저 풀면 &amp;quot; 가 이중 해제된다
}

/* ── 메뉴인가 공고인가 ────────────────────────────────────────────────
   게시판 옆 메뉴('학자금 대출', '장학금 주요사항', '외국인장학금' …)는 공고가 아니다.
   수집기 2종이 반드시 같은 판정을 쓰도록 여기 모아 둔다.

   ⚠️ 2026-08-02에 이 규칙이 갈라져 있어서 사고가 났다. 브라우저 수집기에는 아래 NOTICE_SIGNAL
   우회가 있었는데 일반 수집기에는 없어서, **'…안내'로 끝나는 실공고를 통째로 버리고 있었다**
   (세종대 13건 중 11건, 명지대 10건 중 8건이 이 이유로 사라졌다 — '2026-2 주거안정지원장학금
   신청안내' 같은 진짜 공고들이다). 그래서 두 로봇이 같은 함수를 부르도록 합쳤다. */

/* 메뉴에서 흔한 말꼬리. 단독으로 쓰면 실공고까지 지우므로 반드시 NOTICE_SIGNAL과 함께 판단한다. */
const MENU_NOISE = /안내$|규정$|제도|구분$|바로가기|메뉴|홈페이지$|가이드북|증명서$|융자|^학사\/|장학안내|예우|로그인|사이트맵|^장학\/|장학금·학자금|^학자금 ?대출$|경력개발|비교과|DONATION|기탁/;

/* 실공고 신호 — 연도·날짜·물결(~)·회차·모집/선발/마감/공모가 있으면 제목이 '안내'로 끝나도 공고로 본다
   (예: 경희대 "2026년도 ○○장학금 신청 안내" — 메뉴가 아니라 실공고) */
const NOTICE_SIGNAL = /\d{4}|\d{1,2}[./]\d{1,2}|~|제\d+회|모집|선발|마감|공모/;

/* 연도·학기·회차·기간 표시가 하나도 없으면서 짧으면 옆 메뉴로 본다.
   (2026-08-02 학교 17곳 시험 수집에서 메뉴 20건이 공고로 섞여 들어와 도입.) */
const SHORT_MENU = (t) => !/20\d{2}|\d학기|\d차|~|월\s*\d|제\d/.test(t) && t.replace(/\s/g, '').length <= 16;

/* 순서가 중요하다. '짧고 표시 없음'을 먼저 보지 않으면 '장학생 선발'(아주대 옆 메뉴)이
   NOTICE_SIGNAL의 '선발'에 걸려 공고로 새어 나간다. */
export function isMenuEntry(t) {
  if (SHORT_MENU(t)) return true;                        // 표시 없이 짧으면 메뉴
  return MENU_NOISE.test(t) && !NOTICE_SIGNAL.test(t);   // 말꼬리가 메뉴풍이고 공고 신호도 없으면 메뉴
}

/* ── 목록 행 꼬리 (2026-10-04 개발자 지적 "세종이도만 봐도 이름·날짜·원인 모를 숫자가 제목에 붙어 있네 · 다 수정하고 재발 방지") ──
   이름표 없이 줄 끝에 붙는 작성 부서·작성자·게시일·조회수(항공대 `… 선발 안내 학생지원팀 2026-05-11 1,664` · 국민대 `… 공고 2026.09.08 대전청년내일재단 황새롬`).
   예전엔 확인 로봇의 대조(link-landing stripRowTail)에만 있고 **저장하는 제목에는 없었다** — 그래서 화면에 그대로 떴다. 이제 여기 한 곳이고 stripRowTail 은 이걸 부른다.
   🔴 날짜 앞뒤의 낱말이 기간·안내 낱말이면 제목의 일부다(「셔틀 운행 2026.10.5 중단」 · board-links cutRowTail 과 같은 지킴 목록). */
const DATE = '20\\d{2}[-./]\\d{1,2}[-./]\\d{1,2}\\.?';
const KEEP_WORD = /^(?:까지|부터|마감|이후|이전|예정|안내|휴무|중단|시행|개최|접수|신청|모집|변경|연기|취소|발표|공고|선발|시작|종료|오픈)/;
const WORD = '[가-힣A-Za-z·]{2,15}';
const DEPT = /(?:팀|과|처|실|센터|본부|담당|관리자|사무국|지원단)$/;
const ORG = /(?:재단|장학회|학회|진흥원|공단|협회)$/;
function cutTail(t) {
  let m;
  /* ① 게시일 뒤 작성 부서·작성자 낱말 1~3개 (조회수가 붙어도) */
  /*    🔴 낱말 중 하나는 부서·기관 꼴이어야 한다 — 「장학증서 수여식 안내 2026.09.10 대강당」 의 대강당은 장소다(제목) */
  if ((m = t.match(new RegExp(`\\s+${DATE}((?:\\s+${WORD}){1,4})(?:\\s+[\\d,]+)?\\s*$`)))) {
    const ws = m[1].trim().split(/\s+/);
    if (!ws.some((w) => KEEP_WORD.test(w)) && ws.some((w) => DEPT.test(w) || ORG.test(w))) return t.slice(0, m.index);
  }
  /* ② 작성 부서 낱말 + 게시일 (+ 조회수) — 낱말을 떼는 것은 **조회수가 붙었거나 부서 꼴**일 때만(「문학공모전 2026.08.04」 의 문학공모전은 제목이다) */
  if ((m = t.match(new RegExp(`\\s+(${WORD})\\s+${DATE}(\\s+[\\d,]+)?\\s*$`))) && !KEEP_WORD.test(m[1]) && (m[2] || DEPT.test(m[1]))) return t.slice(0, m.index);
  /* ③ 게시일 (+ 조회수) 만 */
  if ((m = t.match(new RegExp(`\\s+${DATE}(?:\\s+[\\d,]+)?\\s*$`)))) return t.slice(0, m.index);
  return t;
}

function cleanOnce(t) {
  const out = cleanCore(t);   // 문자 기호는 cleanTitle 이 맨 처음 한 번만 푼다(두 번 풀면 &amp;quot; 가 " 가 된다)
  const cut = cutTail(out).replace(/\s+N\s*$/, '').replace(/[\s·\-–—:,|]+$/, '').trim();
  return cut.replace(/\s/g, '').length >= 6 ? cut : out;   // 다 깎여 짧아지면 원래대로 — 제목을 잃는 것보다 꼬리가 남는 편이 낫다
}
/* 🔴 두 번 돌려도 같아야 한다 — 한 번 떼면 다음 꼬리가 드러난다(「… 장학···」 → 「… 장학」 → 분류 꼬리 「장학」).
   감사(verify/title-tails.mjs)가 '저장된 제목을 다시 청소하면 바뀌는가'로 재므로, 여기서 멈출 때까지 돌린다. */
export function cleanTitle(t) {
  let cur = cleanOnce(decodeEntities(t || ''));
  for (let i = 0; i < 4; i += 1) { const next = cleanOnce(cur); if (next === cur) break; cur = next; }
  return cur;
}

/* 실려 있던 글 제목에 지금 청소를 다시 입힌다 — 원칙 7 소급 (2026-10-05 리뷰 · 장학·대외활동·재단 피드 발행 단계 collect.mjs).
   예전엔 소식만(board-links retitleStored) 소급돼, 청소 규칙이 바뀌면(「첨부파일 있음」·폭 없는 공백) 장학 피드에 실린 글은 60일 동안 옛 제목 그대로였다.
   🔴 제목만 고친다 — 주소·글 번호는 그대로(목록 표식 #n- 주소를 다시 만들면 같은 글이 두 번 실렸다 · 2026-10-02). 청소는 멈출 때까지 돌아 두 번 입혀도 같다. */
export function retitleItems(items) {
  for (const n of items || []) if (n && typeof n.title === 'string') n.title = cleanTitle(n.title);
  return items;
}

function cleanCore(t) {
  return String(t || '')
    /* 폭 없는 공백(U+200B·U+FEFF)은 보이지 않는데 제목 앞뒤에 붙어 와 같은 글을 다른 제목으로 만든다 (2026-10-05 점검 news-7 · 항공대·계명대 소식) */
    .replace(/[​﻿]/g, '')
    .replace(/^(공지\s*)+/, '')                        // "공지 공지 " 접두
    /* 목록 열 「첨부파일 있음」(서울대 소식 · 2026-10-05) — 🔴 끝에 붙은 그 두 낱말만. 「(*첨부파일 필독)」 같은 제목 속 말은 그대로 */
    .replace(/\s*첨부파일\s*있음\s*$/, '')
    .replace(/^(?!20[23]\d\s)\d{3,5}\s+/, '')            // 목록 행 번호 "2653 " — 🔴 맨 앞 연도(「2027 해동과학문화재단 …」)는 번호가 아니다 (2026-10-04)
    .replace(/\s*20\d{2}\.\d{1,2}\.\d{1,2}\.?\s*조회\s*\d+\s*$/, '') // 꼬리 "2026.07.08. 조회 136"
    /* 조회수 앞에 홀로 붙은 분류 꼬리표(연세 「… 안내 새글 장학 조회수2 작성일…」)는 조회수와 함께 뗀다 — 🔴 제목 끝의 「공지」·「장학」을 아무 때나 떼지 않는다
       (2026-10-04: 따로 떼던 규칙이 되풀이 청소에서 「… 0번째 공지」·「… 최종선발자 공지」 의 진짜 낱말을 먹었다) */
    .replace(/(?:\s+(?:새글|신규게시글))?(?:\s+(?:장학|학사|일반|공지))?\s*조회수?\s*\d[\s\S]*$/, '')
    .replace(/\s*조회수\s*\d[\s\S]*$/, '')              // "조회수 868 작성일 …" — 뒤는 전부 목록 열
    .replace(/\s*조회\s*\d+[\s\S]*$/, '')
    .replace(/\s*작성일\s*20\d{2}\.[\s\S]*$/, '')
    .replace(/\s*기간\s*[:：]?\s*20\d{2}[.\-][\s\S]*$/, '')   // `기간 : 2026.10.01 ~ 2026.10.31` (정책브리핑 목록)
    .replace(/신규게시글|Attachment|새글/g, '')
    // 구글 머티리얼 아이콘은 글자(check_circle·open_in_new…)로 그려져 제목에 딸려 온다.
    // 강원대에서 '맞춤장학 조회 check_circle'처럼 들어와 메뉴가 공고로 새던 것을 막는다 (2026-08-02).
    // 한글 공고 제목에 snake_case 영문이 들어갈 일은 없으므로 통째로 뗀다.
    .replace(/\b[a-z]{2,}(?:_[a-z]{2,})+\b/g, '')
    .replace(/\s+/g, ' ').trim();
}
