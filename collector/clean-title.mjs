/* 게시판 목록에서 딸려 들어온 부스러기를 제목에서 걷어낸다.

   게시판마다 한 줄(<a> 안)에 번호·분류·조회수·작성일·기간을 함께 넣는 곳이 있어서,
   태그를 걷어내면 전부 한 문장으로 뭉쳐진다. 예(연세대 2026-07-30 연결 시 발견):
     "1383 2026학년도 2학기 염곡문화재단 장학생 추천 안내 새글 장학 조회수 868 작성일 2026.07.24"
   → "2026학년도 2학기 염곡문화재단 장학생 추천 안내"

   수집기(collect.mjs)와 자동 등록(auto-register.mjs)이 같은 규칙을 쓰도록 여기 모아 둔다. */
export function cleanTitle(t) {
  return (t || '')
    .replace(/^(공지\s*)+/, '')                        // "공지 공지 " 접두
    .replace(/^\d{3,5}\s+/, '')                         // 목록 행 번호 "2653 "
    .replace(/\s*20\d{2}\.\d{1,2}\.\d{1,2}\.?\s*조회\s*\d+\s*$/, '') // 꼬리 "2026.07.08. 조회 136"
    .replace(/\s*조회수\s*\d[\s\S]*$/, '')              // "조회수 868 작성일 …" — 뒤는 전부 목록 열
    .replace(/\s*조회\s*\d+[\s\S]*$/, '')
    .replace(/\s*작성일\s*20\d{2}\.[\s\S]*$/, '')
    .replace(/\s*기간\s*20\d{2}\.[\s\S]*$/, '')
    .replace(/신규게시글|Attachment|새글/g, '')
    .replace(/\s+(장학|학사|일반|공지)\s*$/, '')         // 잘라낸 뒤 홀로 남는 분류 꼬리표
    .replace(/\s+/g, ' ').trim();
}
