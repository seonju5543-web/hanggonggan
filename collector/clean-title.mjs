/* 게시판 목록에서 딸려 들어온 부스러기를 제목에서 걷어낸다.

   게시판마다 한 줄(<a> 안)에 번호·분류·조회수·작성일·기간을 함께 넣는 곳이 있어서,
   태그를 걷어내면 전부 한 문장으로 뭉쳐진다. 예(연세대 2026-07-30 연결 시 발견):
     "1383 2026학년도 2학기 염곡문화재단 장학생 추천 안내 새글 장학 조회수 868 작성일 2026.07.24"
   → "2026학년도 2학기 염곡문화재단 장학생 추천 안내"

   수집기(collect.mjs)와 자동 등록(auto-register.mjs)이 같은 규칙을 쓰도록 여기 모아 둔다. */

/* HTML 특수문자를 원래 글자로 되돌린다.
   게시판이 제목에 따옴표·괄호·부등호를 쓰면 HTML에는 &quot; &#40; &lt; 로 들어 있는데,
   태그만 걷어내면 이 글자들이 그대로 남아 앱 화면에 "&quot;근로지담당자&quot;" 처럼 보인다.
   (2026-08-02 가천·가톨릭·경기대를 붙이면서 발견 — 기존 게시판들은 안 쓰던 표기라 여태 안 드러났다) */
function decodeEntities(t) {
  return t
    .replace(/&#(\d+);/g, (_, d) => String.fromCharCode(+d))
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCharCode(parseInt(h, 16)))
    .replace(/&quot;/g, '"').replace(/&apos;/g, "'")
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&');   // 반드시 마지막 — 먼저 풀면 &amp;quot; 가 이중 해제된다
}

/* ── 메뉴인가 공고인가 ────────────────────────────────────────────────
   게시판 옆 메뉴('학자금 대출', '장학금 주요사항', '외국인장학금' …)는 공고가 아니다.
   수집기 2종이 반드시 같은 판정을 쓰도록 여기 모아 둔다.

   ⚠️ 2026-08-02에 이 규칙이 갈라져 있어서 사고가 났다. 브라우저 수집기에는 아래 NOTICE_SIGNAL
   우회가 있었는데 일반 수집기에는 없어서, **'…안내'로 끝나는 실공고를 통째로 버리고 있었다**
   (세종대 13건 중 11건, 명지대 10건 중 8건이 이 이유로 사라졌다 — '2026-2 주거안정지원장학금
   신청안내' 같은 진짜 공고들이다). 그래서 두 로봇이 같은 함수를 부르도록 합쳤다. */

/* 메뉴에서 흔한 말꼬리. 단독으로 쓰면 실공고까지 지우므로 반드시 NOTICE_SIGNAL과 함께 판단한다. */
const MENU_NOISE = /안내$|규정$|제도|구분$|바로가기|메뉴|홈페이지$|가이드북|증명서$|융자|^학사\/|장학안내|예우|로그인|사이트맵|^장학\/|장학금·학자금|^학자금 ?대출$|경력개발|비교과|DONATION|기탁/;

/* 실공고 신호 — 연도·날짜·물결(~)·회차·모집/선발/마감/공모가 있으면 제목이 '안내'로 끝나도 공고로 본다
   (예: 경희대 "2026년도 ○○장학금 신청 안내" — 메뉴가 아니라 실공고) */
const NOTICE_SIGNAL = /\d{4}|\d{1,2}[./]\d{1,2}|~|제\d+회|모집|선발|마감|공모/;

/* 연도·학기·회차·기간 표시가 하나도 없으면서 짧으면 옆 메뉴로 본다.
   (2026-08-02 학교 17곳 시험 수집에서 메뉴 20건이 공고로 섞여 들어와 도입.) */
const SHORT_MENU = (t) => !/20\d{2}|\d학기|\d차|~|월\s*\d|제\d/.test(t) && t.replace(/\s/g, '').length <= 16;

/* 순서가 중요하다. '짧고 표시 없음'을 먼저 보지 않으면 '장학생 선발'(아주대 옆 메뉴)이
   NOTICE_SIGNAL의 '선발'에 걸려 공고로 새어 나간다. */
export function isMenuEntry(t) {
  if (SHORT_MENU(t)) return true;                        // 표시 없이 짧으면 메뉴
  return MENU_NOISE.test(t) && !NOTICE_SIGNAL.test(t);   // 말꼬리가 메뉴풍이고 공고 신호도 없으면 메뉴
}

export function cleanTitle(t) {
  return decodeEntities(t || '')
    .replace(/^(공지\s*)+/, '')                        // "공지 공지 " 접두
    .replace(/^\d{3,5}\s+/, '')                         // 목록 행 번호 "2653 "
    .replace(/\s*20\d{2}\.\d{1,2}\.\d{1,2}\.?\s*조회\s*\d+\s*$/, '') // 꼬리 "2026.07.08. 조회 136"
    .replace(/\s*조회수\s*\d[\s\S]*$/, '')              // "조회수 868 작성일 …" — 뒤는 전부 목록 열
    .replace(/\s*조회\s*\d+[\s\S]*$/, '')
    .replace(/\s*작성일\s*20\d{2}\.[\s\S]*$/, '')
    .replace(/\s*기간\s*20\d{2}\.[\s\S]*$/, '')
    .replace(/신규게시글|Attachment|새글/g, '')
    // 구글 머티리얼 아이콘은 글자(check_circle·open_in_new…)로 그려져 제목에 딸려 온다.
    // 강원대에서 '맞춤장학 조회 check_circle'처럼 들어와 메뉴가 공고로 새던 것을 막는다 (2026-08-02).
    // 한글 공고 제목에 snake_case 영문이 들어갈 일은 없으므로 통째로 뗀다.
    .replace(/\b[a-z]{2,}(?:_[a-z]{2,})+\b/g, '')
    .replace(/\s+(장학|학사|일반|공지)\s*$/, '')         // 잘라낸 뒤 홀로 남는 분류 꼬리표
    .replace(/\s+/g, ' ').trim();
}
