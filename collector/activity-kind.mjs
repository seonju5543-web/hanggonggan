export const ACTIVITY_KINDS = ['공모전', '대외활동'];

/* 공모전 — 내고 심사받는 것 */
const CONTEST = /공모전|공모\s*(?:안내|모집|접수|요강|개최)|아이디어\s*공모|논문\s*공모|영상\s*공모|디자인\s*공모|수기\s*공모|사진\s*공모|작품\s*(?:공모|모집)|경진\s*대회|경연\s*대회|콘테스트|해커톤|아이디어톤|메이커톤|챌린지\s*(?:모집|공고|안내|개최)|\bcontest\b|\bhackathon\b|\bcompetition\b|\bcapstone\b.*(?:대회|경진)/i;

/* 대외활동 — 몸으로 참여하는 것 */
const ACTIVITY = /서포터즈|서포터스|\bsupporters?\b|기자단|홍보대사|앰배서더|\bambassador\b|봉사단|봉사\s*활동|해외\s*봉사|봉사자\s*모집|멘토링|멘토\s*(?:모집|선발)|멘티\s*모집|탐방|캠프|\bcamp\b|연수|참가자\s*모집|참가팀\s*모집|참여\s*(?:학생|자|대학생)\s*모집|체험단|모니터링단|모니터단|평가단|자문단|기획단|운영진\s*모집|리더십\s*(?:프로그램|캠프|과정|스쿨)|워크숍|워크샵|세미나|특강|아카데미|프로그램\s*(?:참가|참여|모집)|교환학생|인턴십|인턴\s*(?:모집|선발)|현장\s*실습|국제\s*교류|교류\s*프로그램|동아리\s*모집|스터디\s*모집|대학생\s*(?:[^\s]+\s*)?(?:단|팀)\s*모집/i;

/* 둘 다 아니다 — 이미 뽑힌 사람에게 보내는 행정 안내, 결과 발표, 채용·대출.
   '멘토링 출근부 마감 안내' 같은 글은 활동 낱말이 있어도 모집이 아니다(실측 · 경희대 게시판). */
const NOT = /출근부|유의사항|교육\s*자료|결과\s*(?:발표|안내|공지)|합격자|선정\s*(?:결과|자)\s*(?:발표|안내|공지)|최종\s*발표|수료증|증명서|채용|구인|아르바이트|알바|대출|융자|취소\s*안내|변경\s*안내|일정\s*변경/;

/* @param title  게시판 글 제목(정리된 것)
   @param opts.scholarship  장학 공고 판정 정규식 — collect.mjs 의 KEYWORDS 를 그대로 넘긴다
                            (여기에 베껴 두면 두 벌이 된다). 안 주면 장학 낱말을 안 본다.
   @returns '공모전' | '대외활동' | null */
export function activityKind(title, opts = {}) {
  const t = String(title || '').trim();
  if (!t) return null;
  if (NOT.test(t)) return null;
  if (CONTEST.test(t)) return '공모전';
  if (opts.scholarship && opts.scholarship.test(t)) return null;
  if (ACTIVITY.test(t)) return '대외활동';
  return null;
}

export default activityKind;
