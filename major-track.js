/* 이름 다듬기 — 캠퍼스 꼬리·괄호 안 설명은 분류에 끼지 않는다. `(공학)`·`(글로벌)` 같은 꼬리는 뗀다.
   ⚠️ 괄호 안이 전공 이름인 경우(`경영학부(글로벌경영학)`)가 있어 **괄호 안도 따로 한 번** 본다. */
function majorNameParts(name) {
  const s = String(name || '').replace(/\s+/g, ' ').trim();
  if (!s) return [];
  const inner = [...s.matchAll(/\(([^)]*)\)/g)].map((m) => m[1].trim()).filter(Boolean);
  const outer = s.replace(/\([^)]*\)/g, '').replace(/\[[^\]]*\]/g, '').replace(/\s*(서울|글로벌|국제|자연|인문|제\d)?캠퍼스\s*$/, '').trim();
  return [outer].concat(inner).filter(Boolean);
}

/** 학과 이름 → 계열 id (data.js TRACKS) · 모르면 null */
function trackOfMajor(name) {
  const parts = majorNameParts(name);
  for (const part of parts) {
    for (const [id, re] of MAJOR_TRACK_RULES) if (re.test(part)) return id;
  }
  return null;
}

/** 학과 목록 → 계열별 학과 수, 많은 순. [{ id, n }] — 하나도 못 가르면 빈 배열 */
function tracksOfMajors(list) {
  const n = new Map();
  for (const m of list || []) {
    const t = trackOfMajor(m);
    if (t) n.set(t, (n.get(t) || 0) + 1);
  }
  return [...n.entries()].sort((a, b) => b[1] - a[1]).map(([id, cnt]) => ({ id, n: cnt }));
}

