//    캡션은 이미 만들어진 `ctx` 만 받는다. CLI 로 직접 돌릴 때만 아래에서 render 를 부른다.

/** 인스타 상한 — 넘으면 게시가 막힌다(글자 2,200 · 해시태그 30). */
export const LIMIT = { chars: 2200, tags: 30 };

/** 재단명·지역에서 해시태그를 만든다. 🔴 큰 태그(#장학금)보다 **작고 정확한 태그**가 낫다 —
 *  계정이 작을 때 큰 태그는 1분이면 밀린다. 그 재단을 검색하는 학생이 실제로 있다. */
/** 🔴 순서가 중요하다 — 괄호를 먼저 지우면 `(재)북청읍장학회` 의 `재` 가 남아
 *  `#재북청읍장학회` 가 된다. 그리고 괄호 **안의 글자도 버린다** —
 *  `강서구장학회(서울)` 이 `#강서구장학회서울` 이 됐다(둘 다 실측). */
const tagify = (s) => '#' + String(s)
  .replace(/^\s*[(（](재|사|주|사단|재단)[)）]\s*/, '')
  .replace(/^(재단법인|사단법인|학교법인|의료법인)\s*/, '')
  .replace(/[(（][^)）]*[)）]/g, '')
  .replace(/[\s·・.,'"]/g, '');

/** 지역 조건에서 지명을 집는다. 🔴 못 찾으면 **지어내지 않고 안 붙인다.**
 *  ⚠️ 함정 둘, 둘 다 실측으로 잡았다:
 *   ① 뒤에 글자가 오면 버리는 규칙 → `익산시에` 의 조사 `에` 때문에 한 건도 안 붙었다.
 *   ② 시·군·구만 보기 → `충남`·`강원도내`·`청송읍`·`금천동`·`대관령면` 을 다 놓쳤다(16건).
 *  🔴 재단 이름에서 지명을 뽑지 않는다 — `손태희장학재단` 처럼 지명이 없는 재단이 많고,
 *     잘못 뽑으면 남의 지역 학생을 끌어들이는 태그가 된다. */
/** 🔴 접미사만 보면 일상어가 지명이 된다 — `반드시`(시) · `학비감면`(면) · `2026학년도`(도)가
 *  실제로 `#반드시장학금` 으로 나왔다. 블랙리스트를 늘리는 것은 끝이 없다.
 *  대신 **재단·공고 이름으로 대조한다**: 뽑은 지명이 그 재단 이름 안에 없으면 안 붙인다.
 *  익산사랑장학재단↔익산시 ✓ · 금천장학회↔금천동 ✓ · 무엇이든↔반드시 ✗.
 *  못 붙이는 쪽으로 틀리는 게 맞다 — 틀린 지역 태그는 남의 동네 학생을 끌어들인다. */
const PROVINCE = '서울|부산|대구|인천|광주|대전|울산|세종|경기|강원|충북|충남|전북|전남|경북|경남|제주'
  + '|경상남|경상북|전라남|전라북|충청남|충청북';
/** 🔴 관문이 이 표를 **받아 간다** — 베끼면 `경상남도장학회 → #경남장학금` 이 근거 없는
 *  태그로 잘못 잡힌다(실제로 그랬다). 검사 규칙 자체는 관문이 따로 갖는다. */
export const SHORTEN = { 경상남: '경남', 경상북: '경북', 전라남: '전남', 전라북: '전북', 충청남: '충남', 충청북: '충북' };
const regionTag = (f, s0) => {
  const t = [f['지역거주구분'], f['특정자격']].map((x) => String(x || '')).join(' ');
  const own = `${s0.org} ${s0.name}`.replace(/\s/g, '');
  // 🔴 조사에 **공백**이 빠지면 `금천동 주민등록`·`양천구 관내` 를 통째로 놓친다(실측 26건).
  const P = '[\\s에의를이가은는로와과내산,./)]|$';
  for (const m of t.matchAll(new RegExp(`([가-힣]{2,4})(특별시|광역시|시|군|구|읍|면|동)(?=${P})`, 'g')))
    if (own.includes(m[1])) return tagify(m[1] + (/시|군|구/.test(m[2]) ? m[2] : '') + '장학금');
  const p = t.match(new RegExp(`(${PROVINCE})(?:특별자치)?도?(?=${P})`));
  if (p) { const n = SHORTEN[p[1]] || p[1]; if (own.includes(n) || own.includes(p[1])) return tagify(n + '장학금'); }
  return null;
};

/** 🔴 렌더러가 판형을 고를 때 쓰는 것과 **같은 씨앗**이다 — 카드와 캡션이 같은 공고에서
 *  늘 같은 얼굴이어야 한다(같은 공고를 두 번 그려도 말투가 안 바뀐다). */
const seedOf = (s0) => [...(s0.org + s0.name)].reduce((a, ch) => (a * 31 + ch.charCodeAt(0)) | 0, 7);

export function caption(s0, c, meta = {}) {
  const f = s0.fields || {};
  // 🔴 마감 지난 공고는 **캡션을 만들지 않는다.** 카드는 '마감 지남' 으로 정직하게 그리면
  //    되지만, 캡션 첫 줄은 신청하라는 말이라 지난 공고에 붙이면 그 자체가 거짓이다.
  if (c.d.state === 'past') throw new Error(`마감이 지난 공고입니다 (${s0.due}) — 올리면 안 됩니다.`);
  const [, mm, dd] = (s0.due || '--').split('-');
  const t2 = String(c.t2).replace(/<[^>]+>/g, '');
  const L = [];
  const p = (...lines) => { if (L.length) L.push(''); L.push(...lines.filter(Boolean)); };

  // 🔴 **매 게시물이 한 글자도 안 다르면 봇 티가 난다.** 표지 후킹을 3종에서 6종으로
  //    늘린 것과 같은 이유로 여기도 씨앗으로 돌린다. 고르는 것은 우리 말투뿐이고
  //    사실은 여전히 원문에서만 온다(원칙 8-1).
  //    ⚠️ 목록마다 **같은 씨앗**을 쓰면 변주들이 서로 붙어 다닌다 — 두 공고가 한 자리에서
  //       같으면 나머지도 전부 같아진다(실측: 한진해운과 수산장학생이 통째로 똑같았다).
  //       목록 자체를 소금으로 섞어 자리마다 따로 움직이게 한다.
  //       🔴 XOR 로 섞으면 안 된다 — 길이가 4면 **하위 2비트**만 보므로 두 목록이
  //          여전히 일대일로 붙는다(관문이 잡았다). 모든 비트가 섞이게 해싱한다.
  const pickOf = (arr) => {
    const salt = [...String(arr[0])].reduce((a, ch) => (a * 31 + ch.charCodeAt(0)) | 0, 0);
    let h = seedOf(s0) ^ salt;
    h = Math.imul(h ^ (h >>> 15), 2246822519);
    h = Math.imul(h ^ (h >>> 13), 3266489917);
    h = (h ^ (h >>> 16)) >>> 0;
    return arr[h % arr.length];
  };

  // ── 1·2줄 — 접히기 전에 보이는 전부 ───────────────────────
  // 🔴 실측(드림스폰 98K, 게시물 3건 대조): 1줄은 브랜드, 2줄은 **저장·팔로우 유도**다.
  //    우리는 팔로워 0이라 1줄에 후킹을 같이 넣는다 — 모르는 사람이 스크롤하다 멈춰야 한다.
  //    🔴 2줄에 '프로필' 이 꼭 들어가야 한다(관문 C8) — 접히기 전 유일한 통로다.
  L.push(`${c.t1} ${t2} · #한대장`);
  L.push(pickOf([
    '일단 저장 📌 나도 되는지는 프로필 링크에서',
    '까먹기 전에 저장 📌 자격 확인은 프로필 링크',
    '저장 먼저 해두세요 📌 되는지는 프로필 링크에서',
    '스크롤 내리기 전에 저장 📌 프로필 링크에서 3초',
  ]));

  // ── 본문 — 짧은 줄 + 빈 줄. 실측: 대부분 10~20자다 ─────────
  // 🔴 **캡션에 자격·조항을 옮겨 적지 않는다**(2026-09-10 개발자 결정).
  //    카드가 이미 전부 싣고 있어서 캡션이 또 쓰면 공고문이 되고, 궁금증을 여기서
  //    풀어 주면 카드를 넘길 이유도 앱을 열 이유도 사라진다.
  // 🔴 `현재 모집중인` 처럼 **지금**을 말하는 표현을 쓰지 말 것 — 게시물은 피드에 남는데
  //    마감 뒤에는 거짓이 된다(표지 후킹에서 상대 날짜를 뺀 것과 같은 이유).
  p(s0.org, s0.name);

  // ⚠️ `~하세요` 를 연달아 쓰면 지시문이 된다(전에 셋이 이어졌다). 서술로 푼다.
  p(c.m && !c.m.many ? `${c.m.n}${c.m.unit} 나오는 장학금이에요.` : '금액은 카드에 적어 뒀어요.',
    c.d.state === 'open' ? `마감은 ${Number(mm)}월 ${Number(dd)}일까지.` : '기간은 카드에서 확인해 주세요.');

  // 🔴 조항 **개수**는 원문에서 센 사실이고, 그 자체가 카드를 넘기게 만드는 후킹이다.
  //    내용은 안 적는다 — 4장이 이 계정의 정체성이라 거기서 읽혀야 한다.
  p(...(c.traps.length
    ? pickOf([
      [`근데 못 받는 조건이 ${c.traps.length}개 붙어 있어요.`, '넘겨보면 바로 나와요'],
      [`걸리면 못 받는 게 ${c.traps.length}개 있어요.`, '넣기 전에 카드 한 번만 넘겨보세요'],
      [`조건에 걸리는 게 ${c.traps.length}개 있더라고요.`, '이거부터 보고 넣으세요'],
    ])
    : pickOf([
      ['신청 조건이 몇 개 붙어 있어요.', '카드 넘기면 바로 나와요'],
      ['조건 몇 개만 보고 넣으면 돼요.', '카드에 정리해 뒀어요'],
    ])));

  p(...pickOf([
    ['"나는 되나?" 싶으면', '프로필 링크 → 한대장', '학과·학년·소득만 넣으면', '되는 것만 딱 남아요'],
    ['자격 하나하나 보기 귀찮으면', '프로필 링크에서 한대장 열어보세요', '넣을 수 있는 것만 골라 줍니다'],
    ['본인이 되는지 3초면 나와요', '프로필 링크 → 학과·학년·소득만', '나머지는 앱이 걸러 줍니다'],
  ]));

  const at = String(meta.updatedAt || '').slice(0, 10).replace(/-/g, '.');
  // 🔴 주소는 클릭이 안 된다. 그래도 어디서 왔는지는 밝힌다 — 이 계정의 무기는 정확함이다.
  p(`출처는 한국장학재단 등재분${at ? ` (${at} 기준)` : ''}이에요.`,
    s0.home ? `원문은 ${s0.home.replace(/^https?:\/\//, '')} 에서 볼 수 있어요.` : null);

  // ⚠️ 마무리가 매번 같으면 홍보 문구로 읽힌다. 사람이 쓴 말처럼 돌려 쓴다.
  p(pickOf([
    '장학금 찾는 시간, 좀 줄여드릴게요 🙂',
    '놓쳐서 못 받는 사람 없었으면 좋겠어요',
    '이번 학기 등록금, 조금이라도 덜어가세요',
    '찾다 지치지 마시고 저희한테 맡겨 주세요 🙂',
  ]));
  p(...pickOf([
    ['● 저장 안 하면 내일 못 찾아요', '● 경희대·한국외대는 교내 장학금도 올라와요', '● 새 공고 놓칠까 봐 매일 올립니다'],
    ['● 일단 저장해두세요', '● 교내 장학금까지 챙기는 계정입니다', '● 마감 임박 공고도 계속 올라와요'],
    ['● 저장 → 마감 전에 다시 보기', '● 경희대·한국외대는 교내까지', '● 매일 새 공고 올라옵니다'],
  ]));

  // ── 해시태그 ─────────────────────────────────────────────
  // 🔴 실측: 드림스폰은 큰 태그 8개를 매번 똑같이 쓴다. 그건 98K 라 되는 것이고,
  //    계정이 0일 때는 큰 태그에서 1분이면 밀린다. **둘을 같이 쓴다** —
  //    작고 정확한 태그(재단·지역)로 지금 걸리고, 큰 태그로 나중에 걸린다. 상한은 30개다.
  const tags = [
    tagify(s0.org), regionTag(f, s0),
    c.d.state === 'open' && c.d.d <= 7 ? '#장학금마감임박' : null,
    '#한대장', '#교외장학금', '#경희대장학금', '#한국외대장학금',
    '#대학생장학금', '#장학금', '#장학금정보', '#대학생지원금',
    '#장학금받자', '#대학생생활비', '#등록금', '#장학금공고',
  ].filter(Boolean);
  p([...new Set(tags)].slice(0, LIMIT.tags).join(' '));

  return L.join('\n');
}

// 🔴 이 파일에 CLI 를 두지 않는다. 캡션 CLI 가 render 를 부르고 render 가 caption 을 부르면
//    **어느 쪽이 진입점이어도 순환 import 로 멈춘다**(둘 다 실제로 겪었다).
//    진입점은 render.mjs 하나다 — `node insta/render.mjs <공고> --caption`.
